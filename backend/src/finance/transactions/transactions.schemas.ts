import { z } from 'zod';
import {
  optionalText,
  positiveMoneySchema,
  uuidSchema,
} from '../../common/schemas.js';

export const transactionTypeSchema = z.enum(['income', 'expense', 'transfer']);

/** Sources the app may report; `recurring` is set only by the server. */
const sourceSchema = z.enum([
  'quick_add',
  'voice',
  'text_ai',
  'receipt_scan',
  'siri',
  'widget',
]);

const instantSchema = z.iso
  .datetime({ offset: true })
  .transform((value) => new Date(value));

/** Units of the user's base currency per one unit of the account currency */
const fxRateSchema = z
  .union([z.number(), z.string().trim()])
  .transform(String)
  .pipe(z.string().regex(/^\d{1,12}(\.\d{1,10})?$/, 'A positive rate'))
  .refine((value) => Number(value) > 0, 'A positive rate');

export const createTransactionSchema = z.object({
  /** Generated by the app, so an offline create can be retried without a double charge */
  id: uuidSchema,
  type: transactionTypeSchema,
  accountId: uuidSchema,
  /** In the account's currency */
  amount: positiveMoneySchema,
  categoryId: uuidSchema.nullable().optional(),
  /** Transfers only: the receiving account */
  transferAccountId: uuidSchema.optional(),
  /** Transfers between currencies: what the receiving account gets; computed from rates when omitted */
  transferAmount: positiveMoneySchema.optional(),
  /** Used when no stored rate exists for the account currency on that date */
  fxRate: fxRateSchema.optional(),
  note: optionalText(255).optional(),
  merchant: optionalText(128).optional(),
  occurredAt: instantSchema,
  source: sourceSchema.default('quick_add'),
});
export type CreateTransactionInput = z.infer<typeof createTransactionSchema>;

export const updateTransactionSchema = z
  .object({
    type: transactionTypeSchema,
    accountId: uuidSchema,
    amount: positiveMoneySchema,
    categoryId: uuidSchema.nullable(),
    transferAccountId: uuidSchema.nullable(),
    transferAmount: positiveMoneySchema.nullable(),
    fxRate: fxRateSchema,
    note: optionalText(255).nullable(),
    merchant: optionalText(128).nullable(),
    occurredAt: instantSchema,
  })
  .partial()
  .refine((patch) => Object.keys(patch).length > 0, 'Nothing to update');
export type UpdateTransactionInput = z.infer<typeof updateTransactionSchema>;

export const listTransactionsQuerySchema = z.object({
  type: transactionTypeSchema.optional(),
  /** Matches both sides of a transfer */
  accountId: uuidSchema.optional(),
  /** Includes its subcategories */
  categoryId: uuidSchema.optional(),
  from: instantSchema.optional(),
  to: instantSchema.optional(),
  /** Note, merchant, category name, or an exact amount */
  q: z.string().trim().min(1).max(100).optional(),
  cursor: z.string().max(200).optional(),
  limit: z.coerce.number().int().min(1).max(200).default(50),
});
export type ListTransactionsQuery = z.infer<typeof listTransactionsQuerySchema>;

export const frequentCategoriesQuerySchema = z.object({
  type: z.enum(['income', 'expense']),
});
