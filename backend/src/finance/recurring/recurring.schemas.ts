import { z } from 'zod';
import {
  optionalText,
  positiveMoneySchema,
  uuidSchema,
} from '../../common/schemas.js';

const calendarDateSchema = z.iso.date();

const schedule = {
  frequency: z.enum(['daily', 'weekly', 'monthly', 'yearly']),
  /** Every N days, weeks, months or years */
  interval: z.number().int().min(1).max(365),
  /** Monthly and yearly: the payment day, 29–31 falling back to the end of shorter months; the start's day when null */
  dayOfMonth: z.number().int().min(1).max(31).nullable(),
  startOn: calendarDateSchema,
  endOn: calendarDateSchema.nullable(),
};

/** A recurring payment or income: Netflix, rent, salary. */
export const createRecurringSchema = z
  .object({
    /** Generated by the app, so an offline create can be retried */
    id: uuidSchema,
    title: z.string().trim().min(1).max(64),
    type: z.enum(['expense', 'income']),
    /** In the account's currency */
    amount: positiveMoneySchema,
    accountId: uuidSchema,
    categoryId: uuidSchema.nullable().default(null),
    ...schedule,
    interval: schedule.interval.default(1),
    dayOfMonth: schedule.dayOfMonth.default(null),
    endOn: schedule.endOn.default(null),
    /** true: the operation is created by itself; false: only a reminder */
    autoCreate: z.boolean().default(false),
    remindDaysBefore: z.number().int().min(0).max(30).default(1),
    isSubscription: z.boolean().default(false),
  })
  .refine((rule) => !rule.endOn || rule.endOn >= rule.startOn, {
    message: 'The end date is before the start',
    path: ['endOn'],
  });
export type CreateRecurringInput = z.infer<typeof createRecurringSchema>;

export const updateRecurringSchema = z
  .object({
    title: z.string().trim().min(1).max(64),
    type: z.enum(['expense', 'income']),
    amount: positiveMoneySchema,
    accountId: uuidSchema,
    categoryId: uuidSchema.nullable(),
    ...schedule,
    autoCreate: z.boolean(),
    remindDaysBefore: z.number().int().min(0).max(30),
    isSubscription: z.boolean(),
    /** A paused rule neither creates operations nor reminds */
    isActive: z.boolean(),
  })
  .partial();
export type UpdateRecurringInput = z.infer<typeof updateRecurringSchema>;

/** «Записать»: the run of `date` happened; the operation gets the app's id. */
export const recordRecurringSchema = z.object({
  transactionId: uuidSchema,
  date: calendarDateSchema,
  /** When this time's amount differs from the rule's */
  amount: positiveMoneySchema.optional(),
  note: optionalText(255).optional(),
});
export type RecordRecurringInput = z.infer<typeof recordRecurringSchema>;

/** «Пропустить»: the run of `date` will not happen. */
export const skipRecurringSchema = z.object({ date: calendarDateSchema });
export type SkipRecurringInput = z.infer<typeof skipRecurringSchema>;
